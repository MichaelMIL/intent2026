"""Simple VRML 3D models (boxes and cylinders) for the footprints that have no model in the KiCad install:
the custom parts in intent.pretty and three stock footprints whose STEP files are not shipped with KiCad 10
(TS-1187A switch, WS2812B-2020, MSK12C02). Output: ../intent.3dshapes/*.wrl

Geometry is authored in footprint coordinates (mm, x right, y DOWN as on the PCB, z up) and converted to the
KiCad VRML convention (0.1 inch units, y up). Dimensions come from the datasheets / JLC footprints.
"""
import os, math

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'intent.3dshapes')
os.makedirs(OUT, exist_ok=True)
U = 1 / 2.54
BLACK = (0.10, 0.10, 0.10)
DARK = (0.20, 0.20, 0.22)
METAL = (0.78, 0.78, 0.80)
WHITE = (0.92, 0.92, 0.88)
BEIGE = (0.90, 0.86, 0.72)
LENS = (0.25, 0.20, 0.20)
YELLOW = (0.95, 0.85, 0.45)


def _pt(x, y, z):
    return '%.4f %.4f %.4f' % (x * U, -y * U, z * U)


def _shape(color, points, faces):
    pts = ', '.join(_pt(*p) for p in points)
    idx = ', '.join(' '.join(str(i) for i in f) + ' -1' for f in faces)
    return ('Shape {\n appearance Appearance { material Material { diffuseColor %.2f %.2f %.2f specularColor 0.3 0.3 0.3 shininess 0.2 } }\n'
            ' geometry IndexedFaceSet { solid FALSE coord Coordinate { point [ %s ] } coordIndex [ %s ] }\n}\n'
            % (color[0], color[1], color[2], pts, idx))


def box(x1, y1, x2, y2, z1, z2, color):
    p = [(x1, y1, z1), (x2, y1, z1), (x2, y2, z1), (x1, y2, z1), (x1, y1, z2), (x2, y1, z2), (x2, y2, z2), (x1, y2, z2)]
    f = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    return _shape(color, p, f)


def cyl(cx, cy, cz, r, length, axis, color, n=24):
    """Cylinder centred at (cx, cy, cz) along axis 'x', 'y' or 'z' with the given length."""
    pts = []
    for k in range(n):
        a = 2 * math.pi * k / n
        for s in (-0.5, 0.5):
            u, v, w = r * math.cos(a), r * math.sin(a), s * length
            if axis == 'z':
                pts.append((cx + u, cy + v, cz + w))
            elif axis == 'x':
                pts.append((cx + w, cy + u, cz + v))
            else:
                pts.append((cx + u, cy + w, cz + v))
    faces = []
    for k in range(n):
        a, b = 2 * k, 2 * ((k + 1) % n)
        faces.append((a, b, b + 1, a + 1))
    faces.append(tuple(2 * k for k in range(n)))
    faces.append(tuple(2 * k + 1 for k in range(n - 1, -1, -1)))
    return _shape(color, pts, faces)


def write(name, body):
    with open(os.path.join(OUT, name + '.wrl'), 'w', newline='\n') as f:
        f.write('#VRML V2.0 utf8\n# %s - generated by 03-kicad/scripts/gen_3d.py (simplified model)\n' % name + body)


